#!/usr/bin/env python3
"""Build a CubeXX debug ramdisk/boot.img/prefix that mirrors boot-stage text to
the panel framebuffer (/dev/fb0) via /grow/fbprint, so a first boot shows running
progress instead of a frozen logo.

The frozen init (tools/release/user_boot_init_h700_display.sh) is NEVER modified.
A debug variant is generated by inserting a guarded say() helper, a one-time
screen clear, and stage markers; every operational command (mounts, grow,
wake_lock, switch_root) is preserved byte-for-byte and asserted unchanged.
Offline only: produces images, never writes a device.
"""
import gzip, hashlib, json, shutil, struct, subprocess, sys
from pathlib import Path

sys.path.insert(0, "/mnt/e/AI/H700Android/tools")
from android_bootimg import read_header, component_offsets, pack as pack_boot
import argparse

FROZEN = Path("/mnt/e/AI/H700Android/tools/release/user_boot_init_h700_display.sh")
WORK = Path("/root/cubexx-build")
RECON = Path("/mnt/e/AI/H700Android/work/cubexx-recon")
INP = WORK / "inputs"
RD = WORK / "rd-debug"
FBPRINT = Path("/mnt/e/AI/H700Android/work/cubexx-build/fbprint.aarch64")
SETLABEL = Path("/mnt/e/AI/H700Android/work/cubexx-build/setlabel.aarch64")


def sha(b):
    return hashlib.sha256(b).hexdigest()


def make_debug_init():
    text = FROZEN.read_text(encoding="utf-8")
    assert "\r" not in text, "frozen init must be LF"

    def sub(anchor, replacement):
        nonlocal text
        assert text.count(anchor) == 1, f"anchor not unique/found: {anchor!r} ({text.count(anchor)})"
        text = text.replace(anchor, replacement, 1)

    # Guarded helper: serial echo + framebuffer line; never fails the boot.
    sub(
        "export PATH=/bin:/sbin:/usr/bin:/usr/sbin\n",
        "export PATH=/bin:/sbin:/usr/bin:/usr/sbin\n"
        "# Debug: mirror stage text to the panel; fbprint failure must not abort boot.\n"
        "say() { echo \"$*\"; /grow/fbprint \"$*\" 2>/dev/null || true; }\n",
    )
    # One-time clear of the stock logo once devtmpfs (and thus /dev/fb0) exists.
    sub(
        "mount -t devtmpfs devtmpfs /dev 2>/dev/null || true\n",
        "mount -t devtmpfs devtmpfs /dev 2>/dev/null || true\n"
        "/grow/fbprint -c 2>/dev/null || true\n"
        "say \"ROC OS CubeXX (H700 1GB 720x720)\"\n",
    )
    # fail(): also surface the error on the panel.
    sub(
        '    echo "[rgsp-single-card] ERROR: $*"\n',
        '    echo "[rgsp-single-card] ERROR: $*"\n'
        '    /grow/fbprint "ERROR: $*" 2>/dev/null || true\n'
        '    /grow/fbprint "Offline recovery required." 2>/dev/null || true\n',
    )
    # Stage markers in execution order.
    sub("echo '[rgsp-single-card] single-card init reached'\n",
        'say "[1/8] single-card init reached"\n')
    sub("DATA_DEV=${TF1}p7\n",
        'DATA_DEV=${TF1}p7\nsay "[2/8] TF1=$TF1 p5/p6/p7 ready"\n')
    sub('/bin/sh /grow/grow-userdata.sh "$TF1" || fail "userdata capacity preparation failed"\n',
        'say "[3/8] grow userdata (auto-expand)"\n'
        '/bin/sh /grow/grow-userdata.sh "$TF1" || fail "userdata capacity preparation failed"\n')
    sub("    /android-root/data || fail \"unable to mount Android data\"\n",
        "    /android-root/data || fail \"unable to mount Android data\"\n"
        'say "[4/8] system/vendor/data mounted"\n')
    sub("if ! /bin/sh /grow/h700-optional-axes.sh",
        'say "[5/8] optional input axes"\nif ! /bin/sh /grow/h700-optional-axes.sh')
    sub("echo '[roc-user-bootfix1] fresh tmpfs dev prepared' >> \"$LOG\"\n",
        'say "[6/8] android dev tmpfs prepared"\n')
    sub("[ -e /android-root/sys/fs/selinux/load ] || fail 'missing SELinux policy load node'\n",
        "[ -e /android-root/sys/fs/selinux/load ] || fail 'missing SELinux policy load node'\n"
        'say "[7/8] SELinux policy node ready"\n')
    sub("echo '[rgsp-single-card] Android root ready; switching root' >> \"$LOG\"\n",
        "echo '[rgsp-single-card] Android root ready; switching root' >> \"$LOG\"\n"
        'say "[8/8] switch_root -> Android init"\n')
    # Debug: capture the kernel ring buffer to a shell-readable file before
    # handing off to enforcing Android init. Opt-in (default OFF, no overhead):
    # enable with `touch /data/local/tmp/kmsg.enable` then reboot; disable by
    # removing that file. The default production boot does not dump kmsg.
    sub(
        "INIT_STARTED_AT=$(awk '{printf \"%d\", $1 * 1000}' /proc/uptime)\n",
        'if [ -f /android-root/data/local/tmp/kmsg.enable ]; then\n'
        '  mkdir -p /android-root/data/local/tmp 2>/dev/null || true\n'
        '  /grow/setlabel /android-root/data/local/tmp 2>/dev/null || true\n'
        '  chmod 0771 /android-root/data/local/tmp 2>/dev/null || true\n'
        '  dmesg > /android-root/data/local/tmp/kmsg.log 2>/dev/null || true\n'
        '  /grow/setlabel /android-root/data/local/tmp/kmsg.log 2>/dev/null || true\n'
        '  chmod 0644 /android-root/data/local/tmp/kmsg.log 2>/dev/null || true\n'
        'fi\n'
        "INIT_STARTED_AT=$(awk '{printf \"%d\", $1 * 1000}' /proc/uptime)\n",
    )

    # Operational invariants must survive unchanged.
    for invariant in [
        '/bin/sh /grow/grow-userdata.sh "$TF1" || fail "userdata capacity preparation failed"',
        'mount -t ext4 -o ro "$SYSTEM_DEV" /android-root ||',
        'mount -t ext4 -o ro "$VENDOR_DEV" /android-root/vendor ||',
        'mount -t ext4 -o rw,noatime,nosuid,nodev,noauto_da_alloc "$DATA_DEV" \\',
        'echo rgsp_android_bringup > /sys/power/wake_lock || fail',
        'exec /bin/busybox switch_root /android-root /init selinux_setup',
        'umask 000',
    ]:
        assert invariant in text, f"operational line lost: {invariant!r}"
    assert "\r" not in text
    return text.encode("utf-8")


def run(cmd, cwd):
    r = subprocess.run(cmd, cwd=cwd, shell=True, capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f"cmd failed ({r.returncode}): {cmd}\n{r.stdout}\n{r.stderr}")
    return r.stdout


def main():
    # 1. Fresh unpack of the project ramdisk (newc cpio) into rd-debug.
    if RD.exists():
        shutil.rmtree(RD)
    RD.mkdir(parents=True)
    tmpl = INP / "boot.raw"
    _, th = read_header(tmpl)
    toff = component_offsets(th)
    raw = tmpl.read_bytes()
    rd_gz = raw[toff["ramdisk"]:toff["ramdisk"] + th["ramdisk_size"]]
    assert rd_gz[:2] == b"\x1f\x8b"
    (RD / "ramdisk.cpio").write_bytes(gzip.decompress(rd_gz))
    run("cpio -idm --no-absolute-filenames --quiet -F ramdisk.cpio", RD)
    (RD / "ramdisk.cpio").unlink()
    orig_init = (RD / "init").read_bytes()
    assert sha(orig_init) == sha(FROZEN.read_bytes()), "ramdisk init != frozen source"

    # 2. Add fbprint binary + debug init.
    shutil.copyfile(FBPRINT, RD / "grow" / "fbprint")
    (RD / "grow" / "fbprint").chmod(0o755)
    shutil.copyfile(SETLABEL, RD / "grow" / "setlabel")
    (RD / "grow" / "setlabel").chmod(0o755)
    debug_init = make_debug_init()
    (RD / "init").write_bytes(debug_init)
    (RD / "init").chmod(0o755)

    # 3. Repack newc cpio + gzip (root ownership preserved by running as root).
    run("find . -print0 | cpio --null -o -H newc --quiet -F ../ramdisk-debug.cpio", RD)
    cpio = (WORK / "ramdisk-debug.cpio").read_bytes()
    rd_new = gzip.compress(cpio, compresslevel=9, mtime=0)
    (WORK / "ramdisk-debug.gz").write_bytes(rd_new)

    # 4. Pack boot.img: stock CubeXX kernel+DTB + debug ramdisk, enforcing cmdline.
    kernel = (RECON / "bootimg_parts" / "kernel").read_bytes()
    dtb = (RECON / "bootimg_parts" / "dtb").read_bytes()
    out_boot = WORK / "cubexx-boot-debug.img"
    pack_boot(argparse.Namespace(template=str(tmpl), out=str(out_boot),
              kernel=str(RECON / "bootimg_parts" / "kernel"),
              ramdisk=str(WORK / "ramdisk-debug.gz"),
              second=None, dtb=str(RECON / "bootimg_parts" / "dtb")))
    newboot = out_boot.read_bytes()
    _, h = read_header(out_boot)
    off = component_offsets(h)
    assert newboot[off["kernel"]:off["kernel"] + h["kernel_size"]] == kernel
    dsz = h.get("dt_size_detected", h["dt_size"])
    assert newboot[off["dtb"]:off["dtb"] + dsz] == dtb
    assert "enforcing" in h["cmdline"] and "permissive" not in h["cmdline"]
    assert len(newboot) == 67108864
    # ramdisk round-trips and contains the debug init + fbprint
    rt = gzip.decompress(newboot[off["ramdisk"]:off["ramdisk"] + h["ramdisk_size"]])
    assert rt == cpio
    assert b"/grow/fbprint" in debug_init and b"[8/8] switch_root" in debug_init

    # 5. Build debug prefix from the known-good cubexx-prefix.raw, swapping boot.
    prefix = bytearray((WORK / "cubexx-prefix.raw").read_bytes())
    assert len(prefix) == 222298112
    prefix[155189248:155189248 + 67108864] = newboot
    dest = WORK / "cubexx-prefix-debug.raw"
    dest.write_bytes(prefix)

    report = {
        "debug_init_bytes": len(debug_init),
        "debug_init_sha256": sha(debug_init),
        "frozen_init_sha256": sha(orig_init),
        "fbprint_bytes": (RD / "grow" / "fbprint").stat().st_size,
        "fbprint_sha256": sha((RD / "grow" / "fbprint").read_bytes()),
        "ramdisk_gz_bytes": len(rd_new),
        "ramdisk_gz_sha256": sha(rd_new),
        "boot_img": {"bytes": len(newboot), "sha256": sha(newboot),
                     "kernel_sha256": sha(kernel), "dtb_sha256": sha(dtb),
                     "cmdline": h["cmdline"]},
        "prefix_debug_sha256": sha(prefix),
        "note": "frozen init unchanged; debug variant adds guarded say()/fbprint only",
    }
    (WORK / "cubexx-prefix-debug.json").write_text(json.dumps(report, indent=2))
    print(json.dumps(report, indent=2))
    print("DEBUG RAMDISK/BOOT/PREFIX OK")


if __name__ == "__main__":
    main()