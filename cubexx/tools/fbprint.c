#define GLYPH 16          /* 8x8 scaled 2x */
#define STATEFILE "/tmp/.fbprint_row"

static int W, H, BPP, LINELEN;
static uint8_t *fb;
static uint8_t *mapbase;
static size_t maplen;
static int roff, rlen, goff, glen, boff, blen;

static uint32_t pix(uint8_t v){
    uint32_t r = (v >> (8 - rlen)) << roff;
    uint32_t g = (v >> (8 - glen)) << goff;
    uint32_t b = (v >> (8 - blen)) << boff;
    return r | g | b;
}
static void putpix(int x, int y, uint32_t p){
    if (x < 0 || y < 0 || x >= W || y >= H) return;
    uint8_t *q = fb + (size_t)y * LINELEN + (size_t)x * (BPP / 8);
    if (BPP == 32) { q[0]=p; q[1]=p>>8; q[2]=p>>16; q[3]=p>>24; }
    else if (BPP == 16) { q[0]=p; q[1]=p>>8; }
    else if (BPP == 24) { q[0]=p; q[1]=p>>8; q[2]=p>>16; }
}
static void clear(void){ memset(fb, 0, (size_t)LINELEN * H); }
static void scroll(void){
    memmove(fb, fb + (size_t)GLYPH * LINELEN, (size_t)(H - GLYPH) * LINELEN);
    memset(fb + (size_t)(H - GLYPH) * LINELEN, 0, (size_t)GLYPH * LINELEN);
}
static void glyph(int cx, int cy, char c){
    if (c < 32 || c > 127) c = '?';
    const uint8_t *g = font8x8[(int)c];
    uint32_t fg = pix(255);
    for (int r = 0; r < 8; r++){
        uint8_t bits = g[r];
        for (int col = 0; col < 8; col++){
            if (bits & (1 << col)){
                int x = cx + col * 2, y = cy + r * 2;
                putpix(x, y, fg); putpix(x+1, y, fg);
                putpix(x, y+1, fg); putpix(x+1, y+1, fg);
            }
        }
    }
}
static int readrow(void){
    int fd = open(STATEFILE, O_RDONLY);
    if (fd < 0) return 0;
    char b[16]; int n = read(fd, b, 15); close(fd);
    if (n <= 0) return 0;
    b[n] = 0; return atoi(b);
}
static void writerow(int r){
    int fd = open(STATEFILE, O_WRONLY | O_CREAT | O_TRUNC, 0644);
    if (fd < 0) return;
    char b[16]; int n = snprintf(b, sizeof b, "%d", r);
    if (n > 0) { ssize_t w = write(fd, b, n); (void)w; }
    close(fd);
}
static void printline(const char *s){
    int maxrows = H / GLYPH, maxcols = W / GLYPH;
    int row = readrow();
    if (row < 0) row = 0;
    if (row >= maxrows){ scroll(); row = maxrows - 1; }
    int cy = row * GLYPH;
    /* clear this line then draw */
    memset(fb + (size_t)cy * LINELEN, 0, (size_t)GLYPH * LINELEN);
    int cx = 0;
    for (const char *p = s; *p && cx < maxcols; p++){
        if (*p == '\n') break;
        if (*p == '\t'){ cx = (cx + 4) & ~3; continue; }
        glyph(cx * GLYPH, cy, *p); cx++;
    }
    writerow(row + 1);
}

int main(int argc, char **argv){
    const char *testfile = getenv("FBPRINT_FILE");
    int fd = -1;
    if (testfile){
        W = getenv("FBPRINT_W") ? atoi(getenv("FBPRINT_W")) : 720;
        H = getenv("FBPRINT_H") ? atoi(getenv("FBPRINT_H")) : 720;
        BPP = getenv("FBPRINT_BPP") ? atoi(getenv("FBPRINT_BPP")) : 32;
        LINELEN = W * (BPP / 8);
        fb = mmap(NULL, (size_t)LINELEN * H, PROT_READ|PROT_WRITE,
                  MAP_PRIVATE|MAP_ANONYMOUS, -1, 0);
        if (fb == MAP_FAILED) return 0;
        mapbase = fb; maplen = (size_t)LINELEN * H;
        memset(fb, 0, (size_t)LINELEN * H);
        roff=16; rlen=8; goff=8; glen=8; boff=0; blen=8;  /* BGRA-ish; test only */
        if (BPP==16){ roff=11; rlen=5; goff=5; glen=6; boff=0; blen=5; }
        /* load existing raw content if present so successive calls accumulate */
        int inf = open(testfile, O_RDONLY);
        if (inf >= 0){ ssize_t n = read(inf, fb, (size_t)LINELEN*H); (void)n; close(inf); }
    } else {
        fd = open("/dev/fb0", O_RDWR);
        if (fd < 0) return 0;
        struct fb_var_screeninfo v; struct fb_fix_screeninfo f;
        if (ioctl(fd, FBIOGET_VSCREENINFO, &v) < 0){ close(fd); return 0; }
        if (ioctl(fd, FBIOGET_FSCREENINFO, &f) < 0){ close(fd); return 0; }
        W = v.xres; H = v.yres; BPP = v.bits_per_pixel;
        LINELEN = f.line_length;
        roff=v.red.offset; rlen=v.red.length;
        goff=v.green.offset; glen=v.green.length;
        boff=v.blue.offset; blen=v.blue.length;
        if (rlen==0||glen==0||blen==0){ close(fd); return 0; }
        fb = mmap(NULL, f.smem_len, PROT_READ|PROT_WRITE, MAP_SHARED, fd, 0);
        if (fb == MAP_FAILED){ close(fd); return 0; }
        mapbase = fb; maplen = f.smem_len;
        fb += (size_t)v.yoffset * LINELEN;
    }

    if (argc >= 2 && strcmp(argv[1], "-c") == 0){
        clear(); writerow(0);
    } else if (argc >= 2){
        printline(argv[1]);
    } else {
        char buf[512];
        ssize_t n = read(0, buf, sizeof(buf)-1);
        if (n > 0){ buf[n]=0; printline(buf); }
    }

    if (testfile){
        int out = open(testfile, O_WRONLY|O_CREAT|O_TRUNC, 0644);
        if (out >= 0){ ssize_t w = write(out, fb, (size_t)LINELEN*H); (void)w; close(out); }
    }
    munmap(mapbase, maplen);
    if (fd >= 0) close(fd);
    return 0;
}